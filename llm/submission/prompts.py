TURN_RE = re.compile(
    r"^\s*(Пользователь|Клиент|Юрист|User|Ассистент|Assistant|Бот)\s*:\s*", re.IGNORECASE | re.MULTILINE
)
ASSISTANT_ROLES = {"ассистент", "assistant", "бот"}


def parse_dialog(question: str) -> list[tuple[str, str]]:
    matches = list(TURN_RE.finditer(question))
    if not matches or matches[0].start() > 0 and question[: matches[0].start()].strip():
        return [("user", question.strip())]
    turns = []
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(question)
        text = question[match.end():end].strip()
        role = "assistant" if match.group(1).lower() in ASSISTANT_ROLES else "user"
        if text:
            turns.append((role, text))
    if not turns or turns[-1][0] != "user":
        return [("user", question.strip())]
    return turns


def retrieval_query(turns: list[tuple[str, str]]) -> str:
    last = turns[-1][1]
    history = " ".join(text for _, text in turns[:-1])
    return f"{last}\n{last}\n{history}".strip()


def _escape(text: str) -> str:
    return text.replace("</документ>", "").replace("</фрагмент>", "").replace("</база_знаний>", "")


def build_messages(
    turns: list[tuple[str, str]],
    company_docs: list[Document],
    company_chunks: list[Chunk],
    law_chunks: list[Chunk],
    docs_by_id: dict[str, Document],
    catalog: str,
) -> list[dict[str, str]]:
    parts = ["<база_знаний>"]
    for doc in company_docs:
        parts.append(f'<документ тип="документ компании" название="{doc.title}">\n{_escape(doc.text)}\n</документ>')
    for chunk in company_chunks:
        parts.append(f'<фрагмент тип="документ компании" метка="{chunk.label}">\n{_escape(chunk.render())}\n</фрагмент>')
    for chunk in law_chunks:
        doc = docs_by_id[chunk.doc_id]
        edition = f' редакция_на="{doc.exported}"' if doc.exported else ""
        changed = f' изменения_статьи="{"; ".join(doc.changes)}"' if doc.changes else ""
        parts.append(
            f'<фрагмент тип="закон, действующая редакция" метка="{chunk.label}" источник="{doc.source}"{edition}{changed}>\n'
            f"{_escape(chunk.render())}\n</фрагмент>"
        )
    if not law_chunks:
        parts.append("(Подходящих фрагментов законов не найдено.)")
    parts.append("</база_знаний>")
    parts.append(
        "Фрагменты законов подобраны автоматически и могут не относиться к вопросу: "
        "используй только те, что действительно нужны для ответа.\n"
        "Полный перечень документов базы знаний (законы приведены выше только частично, "
        "по найденным фрагментам):\n" + catalog
    )
    if len(turns) > 1:
        history = "\n".join(
            f"{'Пользователь' if role == 'user' else 'Ассистент'}: {text}" for role, text in turns[:-1]
        )
        parts.append(f"<история_диалога>\n{_escape(history)}\n</история_диалога>")
    parts.append(f"Вопрос пользователя:\n{turns[-1][1]}")
    parts.append(REMINDER)
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": "\n\n".join(parts)},
    ]


MARKDOWN_RE = re.compile(r"(\*\*|__|^#+\s*|^\s*[-*]\s+(?=\S))", re.MULTILINE)


def clean_answer(text: str) -> str:
    text = MARKDOWN_RE.sub("", text)
    text = re.sub(r"\s*\n\s*", " ", text)
    text = re.sub(r"[ \t]{2,}", " ", text).strip()
    if len(text) > config.MAX_ANSWER_CHARS:
        cut = text.rfind(". ", 0, config.MAX_ANSWER_CHARS)
        text = text[: cut + 1 if cut > 0 else config.MAX_ANSWER_CHARS]
    return text or config.FALLBACK_ANSWER
